# ── 权重分 → 吉凶等级 ──
def score_level(score: float) -> str:
    """权重分 → 吉凶等级（阈值与 palace_score 的「等级」列一致：75/62/48/35）"""
    if score >= 85:
        return "大吉"
    if score >= 75:
        return "吉"
    if score >= 62:
        return "小吉"
    if score >= 48:
        return "平"
    if score >= 35:
        return "凶"
    return "大凶"


# ── ② 程度合成 ──
def degree(miao=None, auxs=None, sihua=None) -> str:
    """程度：庙旺 + 吉/煞辅星 + 四化 → 很强/较强/中等/偏弱/很弱"""
    v = MIAO_DEG.get(miao or "", 0)
    for a in (auxs or []):
        if a in JI_AUX:
            v += 1
        elif a in SHA_AUX:
            v -= 1
    for h in (sihua or []):
        v += SIHUA_DEG.get(h, 0)
    idx = 0 if v <= -3 else 1 if v <= -1 else 2 if v <= 1 else 3 if v <= 3 else 4
    return DEGREES[idx]


def tag(level: str, deg: str) -> str:
    """统一输出：**【吉·较强】**"""
    return f"**【{level}·{deg}】**"


def star_palace_tag(star: str, gong: str, miao=None, auxs=None, sihua=None) -> str:
    lv = STAR_PALACE_LEVEL.get(star, [])
    level = lv[PALACE_ORDER.index(gong)] if gong in PALACE_ORDER and len(lv) == 12 else "平"
    return tag(level, degree(miao, auxs, sihua))


def double_tag(pair: str, miao=None, auxs=None, sihua=None) -> str:
    return tag(DOUBLE_STAR_LEVEL.get(pair, "平"), degree(miao, auxs, sihua))


def sanfang_tag(rule_name: str) -> str:
    # 组合倾向本身已含吉凶；程度按该组合性质给出（大吉大凶=很强，吉凶=较强，平=中等）
    lv = SANFANG_LEVEL.get(rule_name, "平")
    deg = {"大吉": "很强", "大凶": "很强", "吉": "较强", "凶": "较强", "平": "中等"}.get(lv, "中等")
    return tag(lv, deg)


def fu_tag(name: str) -> str:
    lv = FU_XING_LEVEL.get(name, "平")
    return tag(lv, "较强" if lv in ("吉", "凶") else "中等")


def sihua_tag(hua: str, miao=None, auxs=None, sihua=None, doubled=False) -> str:
    lv = SIHUA_LEVEL.get(hua, "平")
    d = degree(miao, auxs, sihua or [hua])
    if doubled and lv == "凶":
        lv, d = "大凶", "很强"
    if doubled and lv == "吉":
        lv, d = "大吉", "很强"
    return tag(lv, d)


def weight_tag(score: float) -> str:
    lv = score_level(score)
    deg = ("很强" if score >= 85 or score < 35 else
           "较强" if score >= 75 or score < 48 else "中等")
    return tag(lv, deg)


def level_of_score(score: float) -> str:
    return score_level(score)


