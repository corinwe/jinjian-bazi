def double_star_of(main_stars: list) -> dict | None:
    """本宫是否双星同宫 → 返回断语条目"""
    names = [s if isinstance(s, str) else s.get("名", "") for s in main_stars]
    if len(names) < 2:
        return None
    key = "".join(names[:2])
    k = _DS_LOOKUP.get(key)
    return {"格": k, **DOUBLE_STAR[k]} if k else None


def sanfang_combo(palace: dict, zmap: dict, sanfang_names: list) -> list:
    """三方四正组合断：返回命中的规则列表"""
    main, aux, sh = [], [], []
    for g in sanfang_names:
        p = zmap.get(g) or {}
        main += [s["名"] for s in p.get("主星", [])]
        aux += [s["名"] for s in p.get("辅星", [])]
        sh += [s["四化"] for s in list(p.get("主星", [])) + list(p.get("辅星", [])) if s.get("四化")]
    alls = main + aux
    hits = []
    for r in SANFANG_RULES:
        n = r["名"]
        ok = False
        if n == "三奇加会":
            ok = all(x in sh for x in ("禄", "权", "科"))
        elif n == "双禄交流":
            ok = ("禄" in sh) and ("禄存" in aux)
        elif n == "禄马交驰":
            ok = ("禄存" in aux) and ("天马" in aux)
        elif n == "贵人明现":
            ok = any(x in aux for x in ("天魁", "天钺"))
        elif n == "左右拱扶":
            ok = any(x in aux for x in ("左辅", "右弼"))
        elif n == "昌曲会照":
            ok = any(x in aux for x in ("文昌", "文曲"))
        elif n == "六吉齐会":
            ok = sum(1 for x in alls if x in JI_STARS) >= 4
        elif n == "火铃加会":
            ok = any(x in aux for x in ("火星", "铃星"))
        elif n == "羊陀加会":
            ok = any(x in aux for x in ("擎羊", "陀罗"))
        elif n == "空劫入局":
            ok = any(x in aux for x in ("地空", "地劫"))
        elif n == "化忌入局":
            ok = "忌" in sh
        elif n == "煞忌交加":
            ok = ("忌" in sh) and (any(x in aux for x in ("火星", "铃星", "擎羊", "陀罗")))
        elif n == "杀破狼联动":
            ok = any(x in main for x in ("七杀", "破军", "贪狼"))
        elif n == "机月同梁联动":
            ok = sum(1 for x in main if x in ("天机", "太阴", "天同", "天梁")) >= 3
