# ── 天干五行（用于解释用神属性）──
GAN_WUXING = {
    "甲": "木", "乙": "木", "丙": "火", "丁": "火", "戊": "土",
    "己": "土", "庚": "金", "辛": "金", "壬": "水", "癸": "水",
}


def get_tiaohou(ri_gan: str, yue_zhi: str, with_detail: bool = False):
    """
    获取调候用神

    参数:
        ri_gan: 日主天干（甲-癸）
        yue_zhi: 月支（寅-丑）
        with_detail: 是否返回备注

    返回:
        with_detail=False: 用神列表 ['壬','甲']
        with_detail=True: (用神列表, 备注)
    """
    ri_gan = ri_gan.strip()
    yue_zhi = yue_zhi.strip()

    if ri_gan not in TIAO_HOU_TABLE:
        raise ValueError(f"未知日干: {ri_gan}")
    if yue_zhi not in TIAO_HOU_TABLE[ri_gan]:
        raise ValueError(f"未知月支: {yue_zhi}")

    gods, note = TIAO_HOU_TABLE[ri_gan][yue_zhi]
    if with_detail:
        return list(gods), note
    return list(gods)


def get_tiaohou_by_month(ri_gan: str, month: int, with_detail: bool = False):
    """按农历月份(1-12)获取调候用神"""
    if month not in MONTH_TO_ZHI:
        raise ValueError(f"未知月份: {month}")
    return get_tiaohou(ri_gan, MONTH_TO_ZHI[month], with_detail)


def explain_tiaohou(ri_gan: str, yue_zhi: str) -> str:
    """生成调候用神的自然语言说明"""
    gods, note = get_tiaohou(ri_gan, yue_zhi, with_detail=True)
    parts = []
    for i, g in enumerate(gods):
        rank = "第一" if i == 0 else ("次" if i == 1 else "辅")
        parts.append(f"{rank}用神{g}（{GAN_WUXING[g]}）")
    return f"{ri_gan}日主生于{yue_zhi}月，调候用神：{'、'.join(gods)}（{'，'.join(parts)}）。{note}"


